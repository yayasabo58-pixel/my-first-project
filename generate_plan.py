def add_content_page(doc, h1, h2, h3, paragraphs, table=None, key=None):
    if h1: add_h1(doc, h1)
    if h2: add_h2(doc, h2)
    if h3: add_h3(doc, h3)
    for p in paragraphs:
        add_body(doc, p)
    if table:
        add_table(doc, table[0], table[1], table[2] if len(table) > 2 else None)
    if key:
        add_key_box(doc, key[0], key[1])
    page_break(doc)

