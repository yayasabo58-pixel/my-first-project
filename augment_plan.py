def style_run(r, east='仿宋', size=14, bold=False, color=None):
    r.font.name='Times New Roman'; r._element.rPr.rFonts.set(qn('w:eastAsia'),east); r.font.size=Pt(size); r.bold=bold
    if color: r.font.color.rgb=RGBColor.from_string(color)

def make_page(part, h2, h3, paragraphs, rows):
    d=Document()
    p=d.paragraphs[0]; p.alignment=WD_ALIGN_PARAGRAPH.CENTER
    r=p.add_run(part); style_run(r,'黑体',18,True,'1F4E79')
    p=d.add_paragraph(); r=p.add_run(h2); style_run(r,'楷体',16,True,'1F4E79')
    p=d.add_paragraph(); r=p.add_run(h3); style_run(r,'楷体',14,False)
    for t in paragraphs:
        p=d.add_paragraph(); p.alignment=WD_ALIGN_PARAGRAPH.JUSTIFY; p.paragraph_format.line_spacing=1.5; p.paragraph_format.space_after=Pt(7)
        r=p.add_run(t); style_run(r)
    table=d.add_table(rows=1,cols=3); table.style='Table Grid'; table.alignment=WD_TABLE_ALIGNMENT.CENTER
    for i,h in enumerate(['分析维度','核心要求','实施重点']):
        c=table.rows[0].cells[i]; c.text=h
        for r in c.paragraphs[0].runs: style_run(r,'仿宋',10.5,True,'FFFFFF')
        c._tc.get_or_add_tcPr().append(__import__('docx').oxml.OxmlElement('w:shd'))
        c._tc.tcPr[-1].set(qn('w:fill'),'1F4E79')
    for row in rows:
        cells=table.add_row().cells
        for i,v in enumerate(row):
            cells[i].text=v
            for r in cells[i].paragraphs[0].runs: style_run(r,'仿宋',10)
    d.add_page_break()
    return [deepcopy(e) for e in d.element.body if e.tag != qn('w:sectPr')]

def find_paragraph(text):
    for p in doc.paragraphs:
        if p.text.strip()==text:
            return p
    raise ValueError(text)

def insert_before(marker, elements):
    p=find_paragraph(marker)
    parent=p._p.getparent(); idx=parent.index(p._p)
    for e in elements:
        parent.insert(idx,e); idx+=1

